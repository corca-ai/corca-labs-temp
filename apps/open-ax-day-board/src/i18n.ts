type MessageKey = keyof typeof messages.ko;

function readStoredLocale(): Locale {
  if (typeof window === "undefined") return "ko";
  try {
    return localStorage.getItem(LOCALE_KEY) === "en" ? "en" : "ko";
  } catch {
    return "ko";
  }
}

let currentLocale: Locale = readStoredLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  try {
    localStorage.setItem(LOCALE_KEY, locale);
  } catch {
    // Language still changes for this session when storage is unavailable.
  }
}

export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  let value = messages[currentLocale][key] ?? messages.ko[key] ?? key;
  if (key === "count.people" && currentLocale === "en") {
    const count = Number(values.count ?? 0);
    return `${count} ${count === 1 ? "person" : "people"}`;
  }
  for (const [name, replacement] of Object.entries(values)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function applyTranslations(root: ParentNode = document): void {
  document.documentElement.lang = currentLocale;
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (key) element.textContent = t(key as MessageKey);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => {
    const key = element.dataset.i18nTitle;
    if (key) element.title = t(key as MessageKey);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (key) element.setAttribute("aria-label", t(key as MessageKey));
  });
  root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]").forEach(
    (element) => {
      const key = element.dataset.i18nPlaceholder;
      if (key) element.placeholder = t(key as MessageKey);
    },
  );
  root.querySelectorAll<HTMLElement>("[data-i18n-corner-label]").forEach((element) => {
    const key = element.dataset.i18nCornerLabel;
    if (key) element.dataset.cornerLabel = t(key as MessageKey);
  });
}
